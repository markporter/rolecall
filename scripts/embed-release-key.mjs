#!/usr/bin/env node
// ADR 0029: write the release verification public key into the source tree
// before building binaries/npm bundles. CI supplies ROLECALL_RELEASE_PUBLIC_KEY;
// local builds leave the default empty array (update verification then requires
// ROLECALL_RELEASE_PUBLIC_KEY at runtime).

import { writeFileSync } from "node:fs";

const key = process.env.ROLECALL_RELEASE_PUBLIC_KEY ?? "";
const path = "src/install/release-key.ts";
writeFileSync(path, `// Generated by scripts/embed-release-key.mjs (ADR 0029).\nexport const EMBEDDED_RELEASE_PUBLIC_KEYS: string[] = ${JSON.stringify(key ? [key] : [])};\n`);
if (!key) console.warn("warning: ROLECALL_RELEASE_PUBLIC_KEY is empty; update signature verification will fail closed");
